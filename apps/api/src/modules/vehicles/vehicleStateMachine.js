import { VEHICLE_STATUSES, ROLES } from '@autobid/config';
import { ValidationError, ForbiddenError } from '../../errors/index.js';

/**
 * Valid state transitions mapping
 */
export const VEHICLE_TRANSITIONS = {
  [VEHICLE_STATUSES.DRAFT]: [VEHICLE_STATUSES.SUBMITTED, VEHICLE_STATUSES.ARCHIVED],
  [VEHICLE_STATUSES.SUBMITTED]: [VEHICLE_STATUSES.UNDER_REVIEW, VEHICLE_STATUSES.DRAFT],
  [VEHICLE_STATUSES.UNDER_REVIEW]: [VEHICLE_STATUSES.INSPECTION, VEHICLE_STATUSES.APPROVED, VEHICLE_STATUSES.DRAFT],
  [VEHICLE_STATUSES.INSPECTION]: [VEHICLE_STATUSES.APPROVED, VEHICLE_STATUSES.UNDER_REVIEW, VEHICLE_STATUSES.DRAFT],
  [VEHICLE_STATUSES.APPROVED]: [VEHICLE_STATUSES.SCHEDULED, VEHICLE_STATUSES.DRAFT],
  [VEHICLE_STATUSES.SCHEDULED]: [VEHICLE_STATUSES.LIVE, VEHICLE_STATUSES.APPROVED],
  [VEHICLE_STATUSES.LIVE]: [VEHICLE_STATUSES.SOLD, VEHICLE_STATUSES.UNSOLD],
  [VEHICLE_STATUSES.SOLD]: [VEHICLE_STATUSES.PAYMENT_PENDING],
  [VEHICLE_STATUSES.UNSOLD]: [VEHICLE_STATUSES.APPROVED, VEHICLE_STATUSES.ARCHIVED],
  [VEHICLE_STATUSES.PAYMENT_PENDING]: [VEHICLE_STATUSES.COMPLETED, VEHICLE_STATUSES.UNSOLD],
  [VEHICLE_STATUSES.COMPLETED]: [VEHICLE_STATUSES.ARCHIVED],
  [VEHICLE_STATUSES.ARCHIVED]: []
};

/**
 * Roles allowed to perform each transition
 */
export const TRANSITION_PERMISSIONS = {
  [`${VEHICLE_STATUSES.DRAFT}->${VEHICLE_STATUSES.SUBMITTED}`]: [ROLES.SELLER, ROLES.DEALER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.SUBMITTED}->${VEHICLE_STATUSES.UNDER_REVIEW}`]: [ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.UNDER_REVIEW}->${VEHICLE_STATUSES.INSPECTION}`]: [ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR, ROLES.INSPECTOR],
  [`${VEHICLE_STATUSES.INSPECTION}->${VEHICLE_STATUSES.APPROVED}`]: [ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR, ROLES.INSPECTOR],
  [`${VEHICLE_STATUSES.UNDER_REVIEW}->${VEHICLE_STATUSES.APPROVED}`]: [ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.UNDER_REVIEW}->${VEHICLE_STATUSES.DRAFT}`]: [ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR], // Rejection
  [`${VEHICLE_STATUSES.APPROVED}->${VEHICLE_STATUSES.SCHEDULED}`]: [ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.SCHEDULED}->${VEHICLE_STATUSES.LIVE}`]: [ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR, 'SYSTEM'],
  [`${VEHICLE_STATUSES.LIVE}->${VEHICLE_STATUSES.SOLD}`]: ['SYSTEM', ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.LIVE}->${VEHICLE_STATUSES.UNSOLD}`]: ['SYSTEM', ROLES.AUCTION_MANAGER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.SOLD}->${VEHICLE_STATUSES.PAYMENT_PENDING}`]: ['SYSTEM', ROLES.FINANCE_MANAGER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.PAYMENT_PENDING}->${VEHICLE_STATUSES.COMPLETED}`]: [ROLES.FINANCE_MANAGER, ROLES.ADMINISTRATOR],
  [`${VEHICLE_STATUSES.COMPLETED}->${VEHICLE_STATUSES.ARCHIVED}`]: [ROLES.ADMINISTRATOR, ROLES.SUPER_ADMINISTRATOR]
};

/**
 * Validates vehicle state transition against state graph and user roles
 */
export function validateVehicleTransition(currentStatus, targetStatus, userRoles = []) {
  if (currentStatus === targetStatus) {
    return true;
  }

  const allowedTargets = VEHICLE_TRANSITIONS[currentStatus] || [];
  if (!allowedTargets.includes(targetStatus)) {
    throw new ValidationError(
      `Invalid vehicle status transition from '${currentStatus}' to '${targetStatus}'. Allowed: [${allowedTargets.join(', ')}]`
    );
  }

  // Super Administrator can perform any valid state transition
  if (userRoles.includes(ROLES.SUPER_ADMINISTRATOR)) {
    return true;
  }

  const transitionKey = `${currentStatus}->${targetStatus}`;
  const allowedRoles = TRANSITION_PERMISSIONS[transitionKey] || [];

  const isAuthorized = userRoles.some(r => allowedRoles.includes(r));
  if (!isAuthorized) {
    throw new ForbiddenError(
      `You do not have permission to transition vehicle from '${currentStatus}' to '${targetStatus}'. Required: [${allowedRoles.join(', ')}]`
    );
  }

  return true;
}
